import { existsSync, writeFileSync } from "node:fs";
import { createInterface } from "node:readline/promises";
import { Keypair } from "@solana/web3.js";
import bs58 from "bs58";

async function main() {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  const ask = async (q: string, dflt = ""): Promise<string> => {
    const suffix = dflt ? ` [${dflt}]` : "";
    const a = (await rl.question(`${q}${suffix}: `)).trim();
    return a || dflt;
  };

  console.log("\n=== copy-trader-sol setup ===\n");

  if (existsSync(".env")) {
    const ok = await ask("An .env already exists. Overwrite? (y/N)", "N");
    if (!ok.toLowerCase().startsWith("y")) {
      console.log("Aborted."); rl.close(); return;
    }
  }

  const heliusKey = await ask("Helius API key (free at helius.dev)");
  const useNew = await ask("Generate a fresh trading wallet? (Y/n)", "Y");
  let secretB58: string;
  let pubkey: string;
  if (useNew.toLowerCase().startsWith("y")) {
    const kp = Keypair.generate();
    secretB58 = bs58.encode(kp.secretKey);
    pubkey = kp.publicKey.toBase58();
    console.log(`\n→ Generated wallet: ${pubkey}`);
    console.log("→ FUND THIS WALLET before starting (Phantom → send SOL to that address)\n");
  } else {
    secretB58 = await ask("Paste base58 secret key (Phantom export)");
    try {
      pubkey = Keypair.fromSecretKey(bs58.decode(secretB58)).publicKey.toBase58();
    } catch {
      console.error("Invalid secret key"); rl.close(); return;
    }
    console.log(`→ Loaded wallet: ${pubkey}`);
  }

  const followed = await ask(
    "Followed wallets (comma-separated, or empty to auto-discover from GMGN)",
  );
  const autoDiscover = followed
    ? await ask("Also auto-discover more from GMGN? (y/N)", "N")
    : "y";

  const size = await ask("SOL per copied buy", "0.02");
  const stopLoss = await ask("Stop-loss % (e.g. 30)", "30");
  const takeProfit = await ask("Take-profit trigger % (e.g. 100 for +100%)", "100");
  const trailingStop = await ask("Trailing stop % from peak (e.g. 20)", "20");
  const maxPos = await ask("Max concurrent positions", "5");
  const dailyLoss = await ask("Daily loss limit in SOL", "0.5");

  const enableTg = await ask("Enable Telegram alerts? (y/N)", "N");
  let tgToken = "", tgChat = "";
  if (enableTg.toLowerCase().startsWith("y")) {
    tgToken = await ask("Telegram bot token (from @BotFather)");
    tgChat = await ask("Telegram chat id (message @userinfobot to get yours)");
  }

  const env = [
    `# Generated by pnpm setup on ${new Date().toISOString()}`,
    `HELIUS_API_KEY=${heliusKey}`,
    `RPC_URL=https://mainnet.helius-rpc.com/?api-key=${heliusKey}`,
    `WS_URL=wss://mainnet.helius-rpc.com/?api-key=${heliusKey}`,
    ``,
    `WALLET_SECRET_KEY=${secretB58}`,
    `# Public address: ${pubkey}`,
    ``,
    `FOLLOWED_WALLETS=${followed}`,
    `AUTO_DISCOVER=${autoDiscover.toLowerCase().startsWith("y") ? "1" : "0"}`,
    `AUTO_DISCOVER_COUNT=5`,
    ``,
    `FIXED_BUY_SOL=${size}`,
    `LEADER_PERCENT=0`,
    `MAX_CONCURRENT_POSITIONS=${maxPos}`,
    `MIN_LEADER_SOL_LAMPORTS=100000000`,
    ``,
    `STOP_LOSS_PCT=${Number(stopLoss) / 100}`,
    `TAKE_PROFIT_PCT=${Number(takeProfit) / 100}`,
    `TRAILING_STOP_PCT=${Number(trailingStop) / 100}`,
    `PRICE_CHECK_INTERVAL_SEC=20`,
    ``,
    `DAILY_LOSS_LIMIT_SOL=${dailyLoss}`,
    `SLIPPAGE_BPS=150`,
    `MIN_LIQUIDITY_USD=25000`,
    `PRIORITY_FEE_MICROLAMPORTS=100000`,
    ``,
    `TELEGRAM_BOT_TOKEN=${tgToken}`,
    `TELEGRAM_CHAT_ID=${tgChat}`,
    ``,
    `ENABLE_DASHBOARD=1`,
    `DASHBOARD_PORT=3000`,
    ``,
    `DRY_RUN=1`,
    `LOG_LEVEL=info`,
    ``,
  ].join("\n");

  writeFileSync(".env", env);
  console.log("\n✓ Wrote .env\n");
  console.log("Next steps:");
  console.log(`  1. Send SOL to ${pubkey} (only what you can lose)`);
  console.log("  2. pnpm dev              # runs with DRY_RUN=1 by default");
  console.log("  3. open http://127.0.0.1:3000");
  console.log("  4. after 24h of clean dry-run, edit .env: DRY_RUN=0");
  console.log(`  5. kill switch: touch ${process.env.HOME}/.copy-trader-kill`);
  rl.close();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
